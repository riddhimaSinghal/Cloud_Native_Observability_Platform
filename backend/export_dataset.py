"""Export the simulated metrics as a CSV dataset (for Zenodo / reports).

Usage:   python export_dataset.py                    -> simulated_metrics.csv
         python export_dataset.py --rows 20000 --out data.csv --seed 7

Rows are generated by the same simulator the app uses (app/collector.py): healthy server
behaviour with injected fault episodes (each 20 samples). Labels come from the simulator,
so they are ground truth for the *simulation*, not for real servers.
"""
import argparse
import csv
import random
from datetime import datetime, timedelta, timezone

from app.collector import Collector, SCENARIOS, SCENARIO_TICKS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=5000)
    ap.add_argument("--out", default="simulated_metrics.csv")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--interval", type=int, default=5, help="seconds between samples (timestamps)")
    a = ap.parse_args()

    rng = random.Random(a.seed)
    col = Collector("simulated", seed=a.seed)
    start = datetime(2026, 1, 1, tzinfo=timezone.utc)
    names = list(SCENARIOS)
    next_fault = rng.randint(60, 200)   # healthy stretch before the first fault
    active = "none"
    left = 0

    with open(a.out, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["timestamp", "cpu_percent", "memory_percent", "disk_percent",
                    "net_in_kbps", "net_out_kbps", "label", "scenario"])
        for i in range(a.rows):
            if left == 0 and i >= next_fault:
                active = rng.choice(names)
                col.start_scenario(active)
                left = SCENARIO_TICKS
            s = col.collect()
            label = "fault" if s["injected"] else "normal"
            w.writerow([(start + timedelta(seconds=i * a.interval)).isoformat(),
                        s["cpu"], s["memory"], s["disk"], s["net_in"], s["net_out"],
                        label, active if s["injected"] else "none"])
            if left:
                left -= 1
                if left == 0:
                    active = "none"
                    next_fault = i + rng.randint(80, 250)
    print(f"Wrote {a.rows} rows to {a.out}")


if __name__ == "__main__":
    main()
